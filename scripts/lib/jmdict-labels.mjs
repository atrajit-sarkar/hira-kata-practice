/**
 * Friendly label for a part-of-speech code; unknown codes are returned unchanged.
 * @param {string} code
 * @returns {string}
 */
export function posLabel(code) {
  return POS_LABELS[code] ?? code;
}

/**
 * English name for an ISO 639-2 language code; unknown codes are returned unchanged.
 * @param {string} code
 * @returns {string}
 */
export function languageName(code) {
  return LANGUAGE_NAMES[code] ?? code;
}
